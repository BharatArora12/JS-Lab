let mood = "happy";

switch (mood) {
    case "happy":
        console.log("Keep smiling! 😊");
        break;

    case "sad":
        console.log("It's okay, better days are coming. 😔");
        break;

    case "angry":
        console.log("Take a deep breath and stay calm. 😡");
        break;

    case "tired":
        console.log("Take some rest. 😴");
        break;

    default:
        console.log("Have a wonderful day! 🙂");
}